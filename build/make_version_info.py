#!/usr/bin/env python3
"""Generate build/version_info.txt — a PyInstaller Windows version resource
— from ``cfdauto.__version__``, the single authoritative version source
(see cfdauto/__init__.py).

This file is regenerated on every build (see build/build.ps1) and is never
hand-edited or committed with a fixed value — that would recreate exactly
the version-duplication problem this sprint is meant to remove.

Run directly for a quick check:

    python build/make_version_info.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from cfdauto import __version__ as VERSION  # noqa: E402


def numeric_tuple(version: str) -> Tuple[int, int, int, int]:
    """Best-effort 4-int tuple for the Windows binary version fields, which
    cannot hold free text like "alpha" — only ``FileVersion``/
    ``ProductVersion`` (the human-readable string fields) carry the exact
    version string.

    "1.0.0-alpha.6" -> (1, 0, 0, 6); "1.0.0" -> (1, 0, 0, 0).
    """
    nums = [int(n) for n in re.findall(r"\d+", version)]
    nums = (nums + [0, 0, 0, 0])[:4]
    return (nums[0], nums[1], nums[2], nums[3])


def render(version: str) -> str:
    filevers = numeric_tuple(version)
    return f'''# UTF-8
#
# Auto-generated by build/make_version_info.py from cfdauto.__version__.
# Do not hand-edit — this file is overwritten on every build.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={filevers!r},
    prodvers={filevers!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
      StringTable(
        u'040904B0',
        [StringStruct(u'CompanyName', u'Slipstream'),
        StringStruct(u'FileDescription', u'Slipstream - CFD Study Manager'),
        StringStruct(u'FileVersion', u'{version}'),
        StringStruct(u'InternalName', u'Slipstream'),
        StringStruct(u'OriginalFilename', u'Slipstream.exe'),
        StringStruct(u'ProductName', u'Slipstream'),
        StringStruct(u'ProductVersion', u'{version}')])
      ]),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
'''


def main() -> int:
    out_path = REPO_ROOT / "build" / "version_info.txt"
    text = render(VERSION)
    out_path.write_text(text, encoding="utf-8")
    print(f"Wrote {out_path} (version={VERSION}, numeric={numeric_tuple(VERSION)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
